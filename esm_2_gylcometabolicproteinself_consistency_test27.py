# 4. Build Mamba-2 Hybrid Model Architecture
# ----------------------------------------------------------------------
def build_mamba2_self_consistency(input_len, d_model=128, d_state=16, n_blocks=3):
    inputs = layers.Input(shape=(input_len, 1))

    # CNN Front-end: Feature Extraction
    x = layers.Conv1D(64, kernel_size=7, padding="same", activation="relu")(inputs)
    x = layers.BatchNormalization()(x)
    x = layers.MaxPooling1D(pool_size=2)(x)

    x = layers.Conv1D(128, kernel_size=5, padding="same", activation="relu")(x)
    x = layers.BatchNormalization()(x)
    x = layers.MaxPooling1D(pool_size=2)(x)

    # Project into Mamba-2 dimension
    x = layers.Dense(d_model)(x)

    # Selective State-Space Backbone
    for _ in range(n_blocks):
        residual = x
        x = layers.LayerNormalization(epsilon=1e-6)(x)
        x = Mamba2Block(d_model=d_model, d_state=d_state)(x)
        x = x + residual

    x = layers.LayerNormalization(epsilon=1e-6)(x)
    x = layers.GlobalAveragePooling1D()(x)

    x = layers.Dense(128, activation="relu")(x)
    outputs = layers.Dense(1, activation="sigmoid")(x)

    mamba2 = models.Model(inputs, outputs, name="Mamba2_SelfConsistency")
    mamba2.compile(
        optimizer=tf.keras.optimizers.Adam(learning_rate=1e-3),
        loss="binary_crossentropy",
        metrics=["accuracy"],
    )
    return mamba2


