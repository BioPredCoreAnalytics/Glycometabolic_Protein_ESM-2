class ChebyKANLayer(layers.Layer):
    """
    Kolmogorov-Arnold layer via Chebyshev polynomials.
    """
    def __init__(self, out_features, degree=5, **kwargs):
        super().__init__(**kwargs)
        self.out_features = out_features
        self.degree = degree

    def build(self, input_shape):
        in_features = int(input_shape[-1])
        self.in_features = in_features

        self.coeffs = self.add_weight(
            name="cheby_coeffs",
            shape=(in_features, self.out_features, self.degree + 1),
            initializer=tf.keras.initializers.RandomNormal(
                mean=0.0, stddev=1.0 / np.sqrt(in_features * (self.degree + 1))
            ),
            trainable=True,
        )
        self.bias = self.add_weight(
            name="bias",
            shape=(self.out_features,),
            initializer="zeros",
            trainable=True,
        )

    def call(self, x):
        # Normalization to Chebyshev domain [-1, 1]
        x = tf.tanh(x)

        # Chebyshev basis expansion
        basis = [tf.ones_like(x), x]
        for _ in range(2, self.degree + 1):
            basis.append(2.0 * x * basis[-1] - basis[-2])
        basis = tf.stack(basis, axis=-1)

        # Tensor dot product combining learned univariate edge functions
        out = tf.einsum("bid,iod->bo", basis, self.coeffs)
        return out + self.bias

    def get_config(self):
        config = super().get_config()
        config.update({"out_features": self.out_features, "degree": self.degree})
        return config


