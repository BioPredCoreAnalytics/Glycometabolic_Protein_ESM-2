# 4. Build High-Capacity Capsule Hybrid Network Architecture
# ----------------------------------------------------------------------
def build_high_capacity_capsule_hybrid(input_len):
    inputs = layers.Input(shape=(input_len, 1))

    # Stage 1: Conv Block with Large Kernel
    x1 = layers.Conv1D(128, kernel_size=9, padding="same", activation="relu")(inputs)
    x1 = layers.BatchNormalization()(x1)

    # Stage 2: Residual Block with Medium Kernel
