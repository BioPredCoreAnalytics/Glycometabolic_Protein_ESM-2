class sLSTMCell(nn.Module):
    """sLSTM cell with exponential gating, ReLU cell updates, and Sigmoid output gating."""
    def __init__(self, hidden_dim):
        super().__init__()
        self.hidden_dim = hidden_dim
        self.w_i = nn.Linear(hidden_dim, hidden_dim)
        self.w_f = nn.Linear(hidden_dim, hidden_dim)
        self.w_o = nn.Linear(hidden_dim, hidden_dim)
        self.w_z = nn.Linear(hidden_dim, hidden_dim)

        self.r_i = nn.Linear(hidden_dim, hidden_dim, bias=False)
        self.r_f = nn.Linear(hidden_dim, hidden_dim, bias=False)
        self.r_o = nn.Linear(hidden_dim, hidden_dim, bias=False)
        self.r_z = nn.Linear(hidden_dim, hidden_dim, bias=False)

    def forward(self, x, state=None):
        batch_size, seq_len, _ = x.shape
        if state is None:
            h = torch.zeros(batch_size, self.hidden_dim, device=x.device)
            c = torch.zeros(batch_size, self.hidden_dim, device=x.device)
            n = torch.zeros(batch_size, self.hidden_dim, device=x.device)
            m = torch.zeros(batch_size, self.hidden_dim, device=x.device)
        else:
            h, c, n, m = state

        outputs = []
        for t in range(seq_len):
            x_t = x[:, t, :]

            # Gating projections
            i_tilde = self.w_i(x_t) + self.r_i(h)
            f_tilde = self.w_f(x_t) + self.r_f(h)
            o_tilde = self.w_o(x_t) + self.r_o(h)

            # ReLU cell candidate modulation
            z_t     = F.relu(self.w_z(x_t) + self.r_z(h))

            # Stabilized exponential gates & Sigmoid output gate
            m_next = torch.maximum(f_tilde + m, i_tilde)
            i_gate = torch.exp(i_tilde - m_next)
            f_gate = torch.exp(f_tilde + m - m_next)
            o_gate = torch.sigmoid(o_tilde)

            c = f_gate * c + i_gate * z_t
            n = f_gate * n + i_gate
            m = m_next

            # ReLU output state activation normalized by state tracking
            h = o_gate * F.relu(c / torch.clamp(n, min=1e-6))
            outputs.append(h.unsqueeze(1))

        outputs = torch.cat(outputs, dim=1)
        return outputs, (h, c, n, m)


class mLSTMCell(nn.Module):
    """mLSTM cell with matrix memory key-value retrieval and Sigmoid gating."""
    def __init__(self, hidden_dim, num_heads=8):
        super().__init__()
        self.hidden_dim = hidden_dim
        self.num_heads = num_heads
        self.head_dim = hidden_dim // num_heads

        self.q_proj = nn.Linear(hidden_dim, hidden_dim)
        self.k_proj = nn.Linear(hidden_dim, hidden_dim)
        self.v_proj = nn.Linear(hidden_dim, hidden_dim)

        self.i_gate = nn.Linear(hidden_dim, num_heads)
        self.f_gate = nn.Linear(hidden_dim, num_heads)
        self.o_gate = nn.Linear(hidden_dim, hidden_dim)

        self.out_proj = nn.Linear(hidden_dim, hidden_dim)

    def forward(self, x):
        batch_size, seq_len, _ = x.shape

        Q = self.q_proj(x).view(batch_size, seq_len, self.num_heads, self.head_dim)
        K = self.k_proj(x).view(batch_size, seq_len, self.num_heads, self.head_dim) / np.sqrt(self.head_dim)
        V = self.v_proj(x).view(batch_size, seq_len, self.num_heads, self.head_dim)

        i = torch.exp(self.i_gate(x))
        f = torch.sigmoid(self.f_gate(x))
        o = torch.sigmoid(self.o_gate(x))

        C = torch.zeros(batch_size, self.num_heads, self.head_dim, self.head_dim, device=x.device)
        outputs = []

        for t in range(seq_len):
            q_t = Q[:, t]
            k_t = K[:, t]
            v_t = V[:, t]
            i_t = i[:, t].unsqueeze(-1).unsqueeze(-1)
            f_t = f[:, t].unsqueeze(-1).unsqueeze(-1)

            kv_outer = torch.matmul(k_t.unsqueeze(-1), v_t.unsqueeze(-2))
            C = f_t * C + i_t * kv_outer

            h_t = torch.matmul(q_t.unsqueeze(-2), C).squeeze(-2)
            h_flat = h_t.view(batch_size, self.hidden_dim)
            outputs.append(h_flat.unsqueeze(1))

        out = torch.cat(outputs, dim=1) * o
        return self.out_proj(out)


class xLSTMBlock(nn.Module):
    def __init__(self, hidden_dim, num_heads=8):
        super().__init__()
        self.ln1 = nn.LayerNorm(hidden_dim)
        self.mlstm = mLSTMCell(hidden_dim, num_heads=num_heads)
        self.ln2 = nn.LayerNorm(hidden_dim)
        self.slstm = sLSTMCell(hidden_dim)

        self.ffn = nn.Sequential(
            nn.Linear(hidden_dim, hidden_dim * 4),
            nn.ReLU(),
            nn.Linear(hidden_dim * 4, hidden_dim)
        )

    def forward(self, x):
        x = x + self.mlstm(self.ln1(x))
        s_out, _ = self.slstm(self.ln2(x))
        x = x + s_out
        x = x + self.ffn(x)
        return x


class xLSTMClassifier(nn.Module):
    def __init__(self, input_dim, seq_len=16, hidden_dim=256, num_classes=2):
        super().__init__()
        self.seq_len = seq_len
        self.chunk_dim = input_dim // seq_len
        self.remainder = input_dim % seq_len

        # Token projection
        self.input_proj = nn.Linear(self.chunk_dim + (1 if self.remainder > 0 else 0), hidden_dim)

        # Deep xLSTM Network
        self.xlstm1 = xLSTMBlock(hidden_dim, num_heads=8)
        self.xlstm2 = xLSTMBlock(hidden_dim, num_heads=8)
        self.xlstm3 = xLSTMBlock(hidden_dim, num_heads=8)

        # Classification Head
        self.head = nn.Sequential(
            nn.LayerNorm(hidden_dim),
            nn.Linear(hidden_dim, 128),
            nn.ReLU(),
            nn.Linear(128, num_classes)
        )

    def forward(self, x):
        batch_size = x.size(0)

        if self.remainder > 0:
            pad_size = self.seq_len - self.remainder
            x_padded = F.pad(x, (0, pad_size))
        else:
            x_padded = x

        chunks = x_padded.view(batch_size, self.seq_len, -1)
        tokens = self.input_proj(chunks)

        x_rec = self.xlstm1(tokens)
        x_rec = self.xlstm2(x_rec)
        x_rec = self.xlstm3(x_rec)

        pooled = torch.mean(x_rec, dim=1) + torch.max(x_rec, dim=1)[0]
        logits = self.head(pooled)
        return logits


