# 5. Distance and Contrastive Loss Definitions
# ----------------------------------------------------------------------
def euclidean_distance(vectors):
    x, y_ = vectors
    sum_sq = tf.reduce_sum(tf.square(x - y_), axis=1, keepdims=True)
    return tf.sqrt(tf.maximum(sum_sq, 1e-9))


def contrastive_loss(margin=1.0):
    def loss(y_true, y_pred):
        y_true = tf.cast(y_true, y_pred.dtype)
        square_pred = tf.square(y_pred)
        margin_square = tf.square(tf.maximum(margin - y_pred, 0.0))
        return tf.reduce_mean(y_true * square_pred + (1.0 - y_true) * margin_square)
    return loss


