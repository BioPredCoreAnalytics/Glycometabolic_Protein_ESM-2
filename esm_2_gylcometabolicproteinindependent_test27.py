# ----------------------------------------------------------------------
# 4. Capsule Network building blocks
# ----------------------------------------------------------------------
def squash(vectors, axis=-1, epsilon=1e-7):
    """Non-linear squashing so capsule vector length in [0,1) represents
    the probability that the entity it represents is present."""
    s_squared_norm = tf.reduce_sum(tf.square(vectors), axis=axis, keepdims=True)
    scale = s_squared_norm / (1.0 + s_squared_norm) / tf.sqrt(s_squared_norm + epsilon)
    return scale * vectors


class PrimaryCapsule(layers.Layer):
    """Conv1D -> reshape into a set of low-level capsule vectors -> squash."""
    def __init__(self, num_channels, dim_capsule, kernel_size=3, strides=2, **kwargs):
        super().__init__(**kwargs)
        self.num_channels = num_channels
        self.dim_capsule = dim_capsule
        self.kernel_size = kernel_size
        self.strides = strides
        self.conv = layers.Conv1D(
            filters=num_channels * dim_capsule,
            kernel_size=kernel_size,
            strides=strides,
            padding="valid",
            activation="relu",
        )

    def call(self, inputs):
        x = self.conv(inputs)                                    # (b, t, channels*dim)
        t = tf.shape(x)[1]
        x = tf.reshape(x, (-1, t * self.num_channels, self.dim_capsule))
        return squash(x)

    def get_config(self):
        config = super().get_config()
        config.update({
            "num_channels": self.num_channels,
            "dim_capsule": self.dim_capsule,
            "kernel_size": self.kernel_size,
            "strides": self.strides,
        })
        return config


class CapsuleRoutingLayer(layers.Layer):
    """Higher-level capsule layer with dynamic routing-by-agreement."""
    def __init__(self, num_capsules, dim_capsule, routings=3, **kwargs):
        super().__init__(**kwargs)
        self.num_capsules = num_capsules
        self.dim_capsule = dim_capsule
        self.routings = routings

    def build(self, input_shape):
        self.input_num_capsules = int(input_shape[1])
        self.input_dim_capsule = int(input_shape[2])
        # transformation matrices: one per (input_capsule, output_capsule) pair
        self.W = self.add_weight(
            shape=(self.input_num_capsules, self.num_capsules,
                   self.dim_capsule, self.input_dim_capsule),
            initializer="glorot_uniform",
            name="routing_weights",
            trainable=True,
        )

    def call(self, inputs):
        # inputs: (batch, input_num_capsules, input_dim_capsule)
        # u_hat: prediction vectors from every input capsule to every output capsule
        u_hat = tf.einsum("bic,ikdc->bikd", inputs, self.W)
        u_hat_stopped = tf.stop_gradient(u_hat)

        batch_size = tf.shape(inputs)[0]
        b = tf.zeros((batch_size, self.input_num_capsules, self.num_capsules))

        v = None
        for r in range(self.routings):
            c = tf.nn.softmax(b, axis=2)                       # coupling coefficients
            use_hat = u_hat if r == self.routings - 1 else u_hat_stopped
            s = tf.einsum("bik,bikd->bkd", c, use_hat)
            v = squash(s)
            if r < self.routings - 1:
                b += tf.einsum("bkd,bikd->bik", v, use_hat)
        return v                                               # (batch, num_capsules, dim_capsule)

    def get_config(self):
        config = super().get_config()
        config.update({
            "num_capsules": self.num_capsules,
            "dim_capsule": self.dim_capsule,
            "routings": self.routings,
        })
        return config


class CapsuleLength(layers.Layer):
    """Length of each output capsule vector = class 'presence' score."""
    def call(self, inputs):
        return tf.sqrt(tf.reduce_sum(tf.square(inputs), axis=-1) + 1e-7)


