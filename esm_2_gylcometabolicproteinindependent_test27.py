    x = CapsuleRoutingLayer(num_capsules=2, dim_capsule=16, routings=3)(x)  # 2 class-capsules
    lengths = CapsuleLength()(x)                      # (batch, 2) -> presence score per class
    outputs = layers.Softmax(name="class_probabilities")(lengths)

    capsule_hybrid = models.Model(inputs, outputs, name="Capsule_Hybrid_Network")
    capsule_hybrid.compile(
        optimizer=tf.keras.optimizers.Adam(learning_rate=1e-3),
        loss="sparse_categorical_crossentropy",
        metrics=["accuracy"],
    )
    return capsule_hybrid


