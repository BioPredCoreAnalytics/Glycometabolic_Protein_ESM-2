def make_pairs(X, y, pairs_per_sample=2, rng=rng):
    """For every sample, create `pairs_per_sample` positive (same-class)
    and `pairs_per_sample` negative (different-class) pairs."""
    class0_idx = np.where(y == 0)[0]
    class1_idx = np.where(y == 1)[0]
    idx_by_class = {0: class0_idx, 1: class1_idx}

    left, right, labels = [], [], []
    n = len(y)
    for i in range(n):
        cls = y[i]
        same_pool = idx_by_class[cls]
        diff_pool = idx_by_class[1 - cls]

        # positive (similar) pairs
        for _ in range(pairs_per_sample):
            j = rng.choice(same_pool)
            left.append(i); right.append(j); labels.append(1)

        # negative (dissimilar) pairs
        for _ in range(pairs_per_sample):
            j = rng.choice(diff_pool)
            left.append(i); right.append(j); labels.append(0)

    left, right, labels = np.array(left), np.array(right), np.array(labels)
    perm = rng.permutation(len(labels))
    left, right, labels = left[perm], right[perm], labels[perm]
    return X[left], X[right], labels.astype("float32")


