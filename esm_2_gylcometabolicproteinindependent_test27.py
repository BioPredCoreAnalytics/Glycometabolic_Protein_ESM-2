    # L2-normalize embeddings -> distances are bounded and well-behaved
    embeddings = layers.Lambda(lambda t: tf.math.l2_normalize(t, axis=1))(embeddings)
    return models.Model(inputs, embeddings, name="Twin_Encoder")


