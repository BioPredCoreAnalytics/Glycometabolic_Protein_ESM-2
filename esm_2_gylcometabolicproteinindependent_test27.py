"""
Mamba-2 (Selective State-Space Model) - Independent Test Model
================================================================================
Dataset : Glycometabolic PVC + ESM-2 features (1433 features + Label)
Split   : 80% Train / 20% Independent Test (stratified, random_state=42)
Batch   : 32
Epochs  : 100
Outputs : Accuracy, Sensitivity(Recall), Specificity, Precision, F1, MCC, AUC
          + ROC curve variables: fpr_mamba, tpr_mamba, roc_auc_mamba

IMPLEMENTATION NOTE (please read):
    There is no official Mamba-2 layer in TensorFlow/Keras (the reference
    implementation uses custom CUDA kernels). This script implements the
    Mamba-2 recurrence -- a SELECTIVE state-space model (SSM) -- from
    scratch with plain TensorFlow ops, following the key architectural
    idea that distinguishes Mamba-2 from Mamba-1:

        Mamba-1 : the state matrix A is a full diagonal, independent
                  per (channel, state) pair.
        Mamba-2 : A is a single SCALAR per channel (shared across all
                  state dimensions) -- the "state-space duality" (SSD)
                  simplification that makes Mamba-2 cheaper and lets it
                  be viewed as a form of structured attention.

    That scalar-per-channel A is exactly what is implemented below,
    together with: input-dependent (selective) discretization step size
    (delta), input-dependent B/C projections, a depthwise causal Conv1D
    "short local context" step, and a gated output (SiLU-gated residual)
    -- all standard Mamba-2 block components.

    Because raw per-timestep recurrence for 1433 steps is expensive on
    CPU, a small CNN front-end first downsamples the sequence (same
    pattern used in the other scripts here) before the Mamba-2 blocks.

IMPORTANT NOTE ON ACCURACY (please read):
    No legitimate script can *guarantee* a fixed accuracy on an independent
    test set -- the real number depends on how separable the two classes
    actually are in this feature space. This script follows solid practice
    (no leakage, early stopping, LR scheduling) to get the best genuine
    result the data supports. Please report whatever number it actually
    produces.
"""

import numpy as np
import pandas as pd
import tensorflow as tf
from tensorflow.keras import layers, models, callbacks
from sklearn.model_selection import train_test_split
from sklearn.preprocessing import StandardScaler
from sklearn.metrics import (accuracy_score, precision_score, recall_score,
                              f1_score, matthews_corrcoef, confusion_matrix,
                              roc_curve, auc, roc_auc_score)
import matplotlib.pyplot as plt

# ----------------------------------------------------------------------
# 0. Reproducibility
# ----------------------------------------------------------------------
SEED = 42
np.random.seed(SEED)
tf.random.set_seed(SEED)

# ----------------------------------------------------------------------
# 1. Load data
# ----------------------------------------------------------------------
DATA_PATH = "/content/GulcoMetabolismESM2_650M_1280Dver27.csv"   # update path if needed
df = pd.read_csv(DATA_PATH)

feature_cols = [c for c in df.columns if c != "Label"]
X = df[feature_cols].values.astype("float64")
y = df["Label"].values.astype("int32")

print(f"Feature matrix : {X.shape}")
print(f"Label counts   : {np.bincount(y)}")

# defensive NaN/inf handling
X = np.nan_to_num(X, nan=0.0, posinf=0.0, neginf=0.0)

# PVC descriptors can reach extreme magnitudes (1e+100+) while ESM-2
# embedding features are small signed floats. arcsinh (signed-log) tames
# the huge dynamic range without breaking sign, and prevents float32
# overflow before scaling.
X = np.arcsinh(X).astype("float32")

# ----------------------------------------------------------------------
# 2. Train / Independent-test split (80/20, stratified)
# ----------------------------------------------------------------------
X_train, X_test, y_train, y_test = train_test_split(
    X, y, test_size=0.2, random_state=SEED, stratify=y
)

# ----------------------------------------------------------------------
# 3. Feature scaling (fit ONLY on train, applied to test -> no leakage)
# ----------------------------------------------------------------------
scaler = StandardScaler()
X_train = scaler.fit_transform(X_train).astype("float32")
X_test = scaler.transform(X_test).astype("float32")

# reshape to (samples, timesteps, channels) for Conv1D front-end
X_train = X_train.reshape(X_train.shape[0], X_train.shape[1], 1)
X_test = X_test.reshape(X_test.shape[0], X_test.shape[1], 1)

n_features = X_train.shape[1]

# ----------------------------------------------------------------------
# 4. Mamba-2 style block (selective SSM with scalar-per-channel A)
# ----------------------------------------------------------------------
class Mamba2Block(layers.Layer):
    def __init__(self, d_model, d_state=16, d_conv=4, expand=2, **kwargs):
        super().__init__(**kwargs)
        self.d_model = d_model
        self.d_state = d_state
        self.d_conv = d_conv
        self.d_inner = expand * d_model

    def build(self, input_shape):
        self.in_proj = layers.Dense(2 * self.d_inner, use_bias=False, name="in_proj")
        self.conv1d = layers.Conv1D(
            filters=self.d_inner, kernel_size=self.d_conv,
            padding="causal", groups=self.d_inner, activation=None, name="short_conv"
        )
        # produces: delta (1), B (d_state), C (d_state) per timestep, per input
        self.x_proj = layers.Dense(1 + 2 * self.d_state, use_bias=False, name="x_proj")
        self.dt_proj = layers.Dense(self.d_inner, use_bias=True, name="dt_proj")

        # Mamba-2: A is a single learnable SCALAR per channel (not per state)
        self.A_log = self.add_weight(
            shape=(self.d_inner,), initializer=tf.keras.initializers.Constant(0.0),
            trainable=True, name="A_log"
        )
        self.D = self.add_weight(
            shape=(self.d_inner,), initializer="ones", trainable=True, name="skip_D"
        )
        self.out_proj = layers.Dense(self.d_model, use_bias=False, name="out_proj")
        super().build(input_shape)

    def call(self, x):
        # x: (batch, seq_len, d_model)
        seq_len = tf.shape(x)[1]

        x_and_res = self.in_proj(x)                        # (b, L, 2*d_inner)
        x_in, res = tf.split(x_and_res, 2, axis=-1)

        x_in = self.conv1d(x_in)[:, :seq_len, :]            # causal short local context
        x_in = tf.nn.silu(x_in)                              # (b, L, d_inner)

        x_dbl = self.x_proj(x_in)                            # (b, L, 1+2*d_state)
        delta, B, C = tf.split(x_dbl, [1, self.d_state, self.d_state], axis=-1)
        delta = tf.nn.softplus(self.dt_proj(delta))          # (b, L, d_inner) - selective step size

        A = -tf.exp(self.A_log)                               # (d_inner,) scalar per channel

        # discretization (Mamba-2 SSD simplification: scalar A broadcasts over d_state)
        deltaA = tf.exp(delta * A)                            # (b, L, d_inner)
        deltaB_u = (delta * x_in)[..., None] * B[:, :, None, :]   # (b, L, d_inner, d_state)

        deltaA_seq = tf.transpose(deltaA, [1, 0, 2])          # (L, b, d_inner)
        deltaBu_seq = tf.transpose(deltaB_u, [1, 0, 2, 3])    # (L, b, d_inner, d_state)

        def scan_step(h_prev, elems):
            dA_t, dBu_t = elems                               # dA_t:(b,d_inner) dBu_t:(b,d_inner,d_state)
            return dA_t[..., None] * h_prev + dBu_t

        h0 = tf.zeros((tf.shape(x)[0], self.d_inner, self.d_state), dtype=x.dtype)
        hs = tf.scan(scan_step, (deltaA_seq, deltaBu_seq), initializer=h0)  # (L,b,d_inner,d_state)
        hs = tf.transpose(hs, [1, 0, 2, 3])                    # (b, L, d_inner, d_state)

        y = tf.reduce_sum(hs * C[:, :, None, :], axis=-1)      # (b, L, d_inner)
        y = y + x_in * self.D                                  # skip connection
        y = y * tf.nn.silu(res)                                # output gate
        return self.out_proj(y)                                # (b, L, d_model)

    def get_config(self):
        config = super().get_config()
        config.update({
            "d_model": self.d_model, "d_state": self.d_state,
            "d_conv": self.d_conv, "expand": self.d_inner // self.d_model,
        })
        return config


