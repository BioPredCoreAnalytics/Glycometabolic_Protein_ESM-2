"""
Siamese Contrastive Network - Independent Test Model
================================================================================
Dataset : Glycometabolic PVC + ESM-2 features (1433 features + Label)
Split   : 80% Train / 20% Independent Test (stratified, random_state=42)
Batch   : 32
Epochs  : 100
Outputs : Accuracy, Sensitivity(Recall), Specificity, Precision, F1, MCC, AUC
          + ROC curve variables: fpr_siamese, tpr_siamese, roc_auc_siamese

How it works:
    1. A shared "twin" encoder network maps every sample to an embedding
       vector. The same encoder weights are used for both inputs of a pair
       (that's what makes it "Siamese").
    2. The network is trained on PAIRS of samples with a contrastive loss:
       pairs from the SAME class are pulled together in embedding space,
       pairs from DIFFERENT classes are pushed apart (beyond a margin).
    3. After training, each training sample's embedding is computed, and
       a class "prototype" (centroid) is built for class 0 and class 1.
    4. Independent test samples are classified by which prototype their
       embedding is closer to; the distance difference is converted into
       a probability score for ROC/AUC.

IMPORTANT NOTE (please read):
    No legitimate script can *guarantee* a fixed accuracy on an independent
    test set -- the real number depends on how separable the two classes
    actually are in this feature space. This script follows solid practice
    (train-only pair sampling and prototypes, no test leakage, early
    stopping, LR scheduling) to get the best genuine result the data
    supports. Please report whatever number it actually produces.
"""

