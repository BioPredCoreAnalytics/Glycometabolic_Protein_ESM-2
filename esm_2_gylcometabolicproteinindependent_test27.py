# 4. ChebyKAN layer  (Kolmogorov-Arnold layer via Chebyshev polynomials)
# ----------------------------------------------------------------------
class ChebyKANLayer(layers.Layer):
    """
    Kolmogorov-Arnold layer: replaces (linear-weight + fixed-activation)
    with a learnable univariate function per (input, output) edge,
    expanded in a Chebyshev polynomial basis of a given degree.
    """
    def __init__(self, out_features, degree=4, **kwargs):
        super().__init__(**kwargs)
        self.out_features = out_features
        self.degree = degree

    def build(self, input_shape):
        in_features = int(input_shape[-1])
        self.in_features = in_features
        # coeffs[i, o, d] = coefficient of Chebyshev poly degree d for edge (i -> o)
        self.coeffs = self.add_weight(
            name="cheby_coeffs",
            shape=(in_features, self.out_features, self.degree + 1),
            initializer=tf.keras.initializers.RandomNormal(
                mean=0.0, stddev=1.0 / (in_features * (self.degree + 1))
            ),
            trainable=True,
        )
        self.bias = self.add_weight(
            name="bias",
            shape=(self.out_features,),
            initializer="zeros",
            trainable=True,
        )

    def call(self, x):
        # squash inputs into [-1, 1], the valid domain of Chebyshev polynomials
        x = tf.tanh(x)

        # build Chebyshev basis T_0..T_degree via the recurrence
        # T_0 = 1, T_1 = x, T_k = 2*x*T_{k-1} - T_{k-2}
        basis = [tf.ones_like(x), x]
        for _ in range(2, self.degree + 1):
            basis.append(2.0 * x * basis[-1] - basis[-2])
        basis = tf.stack(basis, axis=-1)          # (batch, in_features, degree+1)

        # combine per-edge learned functions -> output units
        out = tf.einsum("bid,iod->bo", basis, self.coeffs)
        return out + self.bias

    def get_config(self):
        config = super().get_config()
        config.update({"out_features": self.out_features, "degree": self.degree})
        return config


